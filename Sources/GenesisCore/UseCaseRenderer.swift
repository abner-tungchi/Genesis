import Foundation

public enum UseCaseRenderer {
    /// `sharedImport` is the optional `import {Ctx}Shared` line (empty when no Shared target exists);
    /// passed through to templates whose generated Swift may reference DTO / customType identifiers
    /// (Input fields, CommandExtension param/event types).
    public static func render(
        useCase: UseCaseSpec,
        bundle: FullBundle,
        adapter: Adapter,
        sharedImport: String = ""
    ) throws -> [(path: String, content: String, role: String)] {
        let ucName = CaseTransformer.upperCamel(useCase.useCase)
        let ucCamel = CaseTransformer.lowerCamel(useCase.useCase)
        let aggregate = useCase.aggregate
        let eventTypeName = CaseTransformer.upperCamel(useCase.emittedEvent)
        let knownCustomTypes = bundle.dtoTypeNames.union(adapter.customTypes.map { $0.name })

        let inputDir = "Sources/\(aggregate)Aggregate/Usecase/Port/In/\(ucName)"

        // Phase 1.l: lookup aggregate.identityName to auto-inject aggId field into UsecaseInput (OC alignment).
        guard let agg = bundle.aggregates.first(where: { $0.aggregateSpecId == useCase.aggregateSpecId }) else {
            throw GenesisError.bundleInvalid(
                reason: "useCase '\(useCase.useCase)' aggregateSpecId '\(useCase.aggregateSpecId)' not found in bundle.aggregates"
            )
        }
        let aggIdName = agg.identityName

        // Phase 1.l.1: create UC heuristic — name prefix "create" or "establish"
        // (matches /usecase skill convention; 100% of OC/IAM dogfood UC follow this)
        // Used to skip aggId injection in renderInput — create UC aggregate id is
        // generated by Service via UUID(), not passed in by caller.
        let isCreateUseCase = ucCamel.hasPrefix("create") || ucCamel.hasPrefix("establish")

        var outputs: [(String, String, String)] = []

        outputs.append(try renderInput(
            uc: ucName, fields: useCase.input,
            aggIdName: aggIdName,
            adapter: adapter, knownCustomTypes: knownCustomTypes,
            sharedImport: sharedImport, dir: inputDir
        ))
        outputs.append(try renderOutput(uc: ucName, dir: inputDir))
        let executeBody = buildExecuteBody(
            ucCamel: ucCamel,
            aggregate: aggregate,
            aggIdName: aggIdName,
            commandFields: useCase.input,
            isCreateUseCase: isCreateUseCase
        )
        outputs.append(try renderUsecase(uc: ucName, aggregate: aggregate, sharedImport: sharedImport, executeBody: executeBody, dir: inputDir))
        outputs.append(try renderService(uc: ucName, aggregate: aggregate))

        // Phase 1.t / D6: do NOT generate a command extension for create UCs.
        // The plugin-generated aggregate protocol does not dispatch the Created event to when(event:)
        // (Created is handled by the rehydration init), so a create command method + when(Created) is
        // dead scaffold. OC AuditQuotingAggregate has no create command file either.
        if !isCreateUseCase {
            outputs.append(try renderCommandExtension(
                uc: ucName,
                ucCamel: ucCamel,
                aggregate: aggregate,
                eventTypeName: eventTypeName,
                commandFields: useCase.input,
                stateFields: agg.state,
                payloadFields: useCase.eventPayload,
                preconditions: useCase.preconditions,
                adapter: adapter,
                knownCustomTypes: knownCustomTypes,
                sharedImport: sharedImport
            ))
        }

        return outputs
    }

    private static func renderInput(
        uc: String,
        fields: [FieldSpec],
        aggIdName: String,
        adapter: Adapter,
        knownCustomTypes: Set<String>,
        sharedImport: String,
        dir: String
    ) throws -> (String, String, String) {
        // Canonical Input field set (aggId + business + operatorId) — SINGLE SOURCE shared with FixtureRenderer
        // so a fixture's `.init(...)` call args match this `<UC>Input.init` param order BY CONSTRUCTION. See
        // `canonicalInputFields`.
        let canonicalFields = canonicalInputFields(fields: fields, aggIdName: aggIdName)

        var decls: [String] = []
        var initParamsParts: [String] = []
        var assignments: [String] = []
        for field in canonicalFields {
            let resolved = try SwiftTypeResolver.resolve(
                rawType: field.rawType, knownCustomTypes: knownCustomTypes, adapter: adapter
            )
            decls.append("    package let \(field.name): \(resolved)")
            initParamsParts.append("\(field.name): \(resolved)")
            assignments.append("        self.\(field.name) = \(field.name)")
        }

        let template = try TemplateLoader.loadTemplate(name: "UsecaseInput.swift", ext: "template")
        let rendered = TemplateRenderer.render(
            template: template,
            vars: [
                "UC": uc,
                "SharedImport": sharedImport,
                "InputFieldDecls": decls.joined(separator: "\n"),
                "InitParams": initParamsParts.joined(separator: ", "),
                "InitAssignments": assignments.joined(separator: "\n"),
            ]
        )
        return ("\(dir)/\(uc)Input.swift", rendered.output, "usecaseInput")
    }

    /// The canonical Usecase Input field set, shared by `renderInput` and `FixtureRenderer` so a fixture's
    /// `.init(...)` call args match the generated `<UC>Input.init` param order BY CONSTRUCTION (Swift requires
    /// labeled-init args in declared order — a copied derivation that drifts would mis-order args and fail only
    /// at the downstream generated project's build). Ordering (Phase 1.l audit M4 / Phase 1.t.3 PA-F6): aggId
    /// first, business fields middle, operatorId last. Create UC Input ALSO carries the (caller-provided) aggId
    /// (aligned with OC CreateAuditQuotingInput.quotingId). The filter dedupes a user-supplied aggId/operatorId
    /// already present in `useCase.input` to avoid double-emit.
    static func canonicalInputFields(fields: [FieldSpec], aggIdName: String) -> [FieldSpec] {
        let businessFields = fields.filter { $0.name != aggIdName && $0.name != "operatorId" }
        let aggIdField = FieldSpec(name: aggIdName, rawType: "String")
        let operatorIdField = FieldSpec(name: "operatorId", rawType: "String")
        return [aggIdField] + businessFields + [operatorIdField]
    }

    private static func renderOutput(uc: String, dir: String) throws -> (String, String, String) {
        let template = try TemplateLoader.loadTemplate(name: "UsecaseOutput.swift", ext: "template")
        let rendered = TemplateRenderer.render(template: template, vars: ["UC": uc])
        return ("\(dir)/\(uc)Output.swift", rendered.output, "usecaseOutput")
    }

    private static func renderUsecase(uc: String, aggregate: String, sharedImport: String, executeBody: String, dir: String) throws -> (String, String, String) {
        let template = try TemplateLoader.loadTemplate(name: "Usecase.swift", ext: "template")
        let rendered = TemplateRenderer.render(
            template: template,
            vars: [
                "UC": uc,
                "Aggregate": aggregate,
                "useCaseCamelCase": CaseTransformer.lowerCamel(uc),
                "SharedImport": sharedImport,
                "ExecuteBody": executeBody,
            ]
        )
        return ("\(dir)/\(uc)Usecase.swift", rendered.output, "usecase")
    }

    /// Phase 1.x / D1: emit the deterministic orchestration body for execute() at codegen time
    /// (replaces the old `fatalError("TODO(/usecase skill)")` stub). The body is pure orchestration
    /// (find → command → save → return + catch ladder), fully derivable from the same `useCase.input`
    /// that drives the Input type and the command signature — so the call args match by construction.
    /// Business logic stays in the command/when/ensureInvariant `#error` holes (filled by /domain-fill).
    private static func buildExecuteBody(
        ucCamel: String,
        aggregate: String,
        aggIdName: String,
        commandFields: [FieldSpec],
        isCreateUseCase: Bool
    ) -> String {
        let agg = CaseTransformer.lowerCamel(aggregate)
        let A = aggregate
        // useCase.input = aggId + business (no operatorId; renderInput synthesizes operatorId into Input).
        let businessFields = commandFields.filter { $0.name != aggIdName && $0.name != "operatorId" }

        // Phase 1.y: rethrow GenesisTODO BEFORE the catch-all, else the marker is wrapped into
        // DDDError.executeUsecaseFailed and the test sees an opaque DDDError instead of the distinctive
        // GenesisTODO type (the #expect(throws: ContextError<X>) red would then be indistinguishable from a
        // real failure). One shared ladder covers create/delete/update — this single rethrow fixes all three.
        let catchLadder = """
                } catch let error as GenesisTODO {
                    throw error
                } catch let error as ContextError<\(A)Error> {
                    throw error
                } catch let error as DDDError {
                    throw error
                } catch {
                    throw DDDError.executeUsecaseFailed(usecase: self, input: input, userInfos: ["error": error])
                }
        """

        if isCreateUseCase {
            // Create: construct the aggregate via its (convenience or designated) init — id is caller-provided
            // input.<aggId>; non-id init params == input business fields (same filter AggregateRenderer uses).
            let initArgs = ([("id", aggIdName)] + businessFields.map { ($0.name, $0.name) })
                .map { "\($0.0): input.\($0.1)" }
                .joined(separator: ", ")
            return """
                    do {
                        let \(agg) = try \(A)(\(initArgs))
                        try await repository.save(aggregateRoot: \(agg), userId: input.operatorId)
                        return .init(id: input.\(aggIdName), message: nil)
            \(catchLadder)
            """
        }

        if ucCamel.lowercased().hasPrefix("delete") {
            return """
                    guard let \(agg) = try await repository.find(byId: input.\(aggIdName)) else {
                        throw DDDError.aggregateNotFound(usecase: self, aggregateRootType: \(A).self, aggregateRootId: input.\(aggIdName))
                    }
                    do {
                        try await repository.delete(byId: \(agg).id, userId: input.operatorId)
                        return .init(id: \(agg).id)
            \(catchLadder)
            """
        }

        // Update: call the command method with the EXACT commandFields (= useCase.input) it was generated from.
        let callArgs = commandFields.map { "\($0.name): input.\($0.name)" }.joined(separator: ", ")
        return """
                guard let \(agg) = try await repository.find(byId: input.\(aggIdName)) else {
                    throw DDDError.aggregateNotFound(usecase: self, aggregateRootType: \(A).self, aggregateRootId: input.\(aggIdName))
                }
                do {
                    try \(agg).\(ucCamel)(\(callArgs))
                    try await repository.save(aggregateRoot: \(agg), userId: input.operatorId)
                    return .init(id: \(agg).id, message: nil)
        \(catchLadder)
        """
    }

    private static func renderService(uc: String, aggregate: String) throws -> (String, String, String) {
        let template = try TemplateLoader.loadTemplate(name: "Service.swift", ext: "template")
        let rendered = TemplateRenderer.render(
            template: template,
            vars: [
                "UC": uc,
                "Aggregate": aggregate,
            ]
        )
        let path = "Sources/\(aggregate)Aggregate/Usecase/Service/\(uc)Service.swift"
        return (path, rendered.output, "service")
    }

    private static func renderCommandExtension(
        uc: String,
        ucCamel: String,
        aggregate: String,
        eventTypeName: String,
        commandFields: [FieldSpec],
        stateFields: [FieldSpec],
        payloadFields: [FieldSpec],
        preconditions: [String],
        adapter: Adapter,
        knownCustomTypes: Set<String>,
        sharedImport: String
    ) throws -> (String, String, String) {
        var paramParts: [String] = []
        for field in commandFields {
            let resolved = try SwiftTypeResolver.resolve(
                rawType: field.rawType, knownCustomTypes: knownCustomTypes, adapter: adapter
            )
            paramParts.append("\(field.name): \(resolved)")
        }
        let commandParams = paramParts.joined(separator: ", ")

        let preconditionScaffold = buildPreconditionScaffold(preconditions: preconditions, aggregate: aggregate)

        let whenBody = try buildWhenBody(
            eventTypeName: eventTypeName,
            stateFields: stateFields,
            payloadFields: payloadFields,
            adapter: adapter,
            knownCustomTypes: knownCustomTypes
        )

        let template = try TemplateLoader.loadTemplate(name: "CommandExtension.swift", ext: "template")
        let rendered = TemplateRenderer.render(
            template: template,
            vars: [
                "Aggregate": aggregate,
                "SharedImport": sharedImport,
                "useCaseCamelCase": ucCamel,
                "CommandParams": commandParams,
                "EventTypeName": eventTypeName,
                "PreconditionScaffold": preconditionScaffold,
                "WhenBody": whenBody,
            ]
        )
        let path = "Sources/\(aggregate)Aggregate/Entity/Commands/\(aggregate)+\(uc).swift"
        return (path, rendered.output, "commandExtension")
    }

    /// Phase 1.u / A1: emit bundle `preconditions` into the command body as comment scaffold + a DOMAIN marker.
    /// errorCode is NOT auto-wired (D5): precondition NL → ContextError case is a semantic, not structural,
    /// mapping, and generated ContextError factories come only from aggregate invariants — auto-wiring would
    /// invent/guess a case that may not exist. The human/LLM picks the case when filling the #error hole.
    private static func buildPreconditionScaffold(preconditions: [String], aggregate: String) -> String {
        guard !preconditions.isEmpty else {
            return "        // PRECONDITION (from bundle): none declared."
        }
        var lines: [String] = []
        for p in preconditions {
            let oneLine = p.replacingOccurrences(of: "\n", with: " ")
            lines.append("        // PRECONDITION (from bundle): \(oneLine)")
        }
        lines.append("        // DOMAIN: implement the guard(s) above; throw the matching ContextError<\(aggregate)Error> case.")
        return lines.joined(separator: "\n")
    }

    /// Phase 1.t / D5 + Phase 1.y: emit a strict-safe scalar reducer body, else a TDD throw-marker.
    /// strict-safe = every event-payload field 1:1-maps to a mutable aggregate state field:
    /// same name, same resolved type, NOT a collection (Set/Array), NOT a `new*`/`old*` semantic-rename.
    /// If ALL payload fields are strict-safe → `self.<f> = event.<f>` for each; otherwise (incl. empty payload —
    /// a zero-payload event may still need a deterministic state change, so it stays fail-loud) the reducer
    /// becomes a structure comment + `throw GenesisTODO.notImplemented(...)` — compiles (TDD: the reducer's test
    /// goes RED) instead of #error blocking the whole build.
    private static func buildWhenBody(
        eventTypeName: String,
        stateFields: [FieldSpec],
        payloadFields: [FieldSpec],
        adapter: Adapter,
        knownCustomTypes: Set<String>
    ) throws -> String {
        var stateTypeByName: [String: String] = [:]
        for f in stateFields {
            stateTypeByName[f.name] = try SwiftTypeResolver.resolve(
                rawType: f.rawType, knownCustomTypes: knownCustomTypes, adapter: adapter
            )
        }

        var assignments: [String] = []
        var allStrictSafe = !payloadFields.isEmpty
        for p in payloadFields {
            let resolved = try SwiftTypeResolver.resolve(
                rawType: p.rawType, knownCustomTypes: knownCustomTypes, adapter: adapter
            )
            let lname = p.name.lowercased()
            let isCollection = resolved.contains("Set<") || resolved.contains("[")
            let isSemanticRename = lname.hasPrefix("new") || lname.hasPrefix("old")
            guard let stateType = stateTypeByName[p.name],
                  stateType == resolved,
                  !isCollection,
                  !isSemanticRename
            else {
                allStrictSafe = false
                break
            }
            assignments.append("        self.\(p.name) = event.\(p.name)")
        }

        if allStrictSafe {
            return assignments.joined(separator: "\n")
        }
        return "        // \(eventTypeName) state transition is not strict-safe "
            + "(empty payload / collection / type-mismatch / new-old rename / nested).\n"
            + "        // DOMAIN: assign the relevant self.<field> from event.<field> (with any needed conversion / collection op).\n"
            + "        throw GenesisTODO.notImplemented(\"when(\(eventTypeName)) state transition\")"
    }
}
