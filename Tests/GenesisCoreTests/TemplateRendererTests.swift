import XCTest
@testable import GenesisCore

final class TemplateRendererTests: XCTestCase {
    func testSingleVar() {
        let result = TemplateRenderer.render(template: "hello {name}", vars: ["name": "world"])
        XCTAssertEqual(result.output, "hello world")
        XCTAssertEqual(result.unresolvedVariables, [])
    }

    func testMissingVar() {
        let result = TemplateRenderer.render(template: "hello {name}", vars: [:])
        XCTAssertEqual(result.output, "hello {name}")
        XCTAssertEqual(result.unresolvedVariables, ["name"])
    }

    func testMultipleVarsAndDuplicates() {
        let result = TemplateRenderer.render(
            template: "{a} {a} {b}",
            vars: ["a": "1", "b": "2"]
        )
        XCTAssertEqual(result.output, "1 1 2")
        XCTAssertEqual(result.unresolvedVariables, [])
    }

    func testMixedResolvedAndUnresolved() {
        let result = TemplateRenderer.render(
            template: "{a} and {b}",
            vars: ["a": "ok"]
        )
        XCTAssertEqual(result.output, "ok and {b}")
        XCTAssertEqual(result.unresolvedVariables, ["b"])
    }

    func testNoVariables() {
        let result = TemplateRenderer.render(template: "plain text", vars: ["x": "y"])
        XCTAssertEqual(result.output, "plain text")
        XCTAssertEqual(result.unresolvedVariables, [])
    }

    func testRenderActualPackageSwiftTemplate() throws {
        // Phase 1.b added {ProductsList} and {TargetsList} placeholders to the template.
        // Caller (PackageRenderer) is expected to compute these from per-aggregate sub-templates
        // and pass them in. We pass empty strings here just to verify the main template renders.
        let template = try TemplateLoader.loadPackageSwiftTemplate()
        let result = TemplateRenderer.render(
            template: template,
            vars: [
                "ContextName": "IAMContext",
                "GenesisVersion": "0.0.1-test",
                "ProductsList": "",
                "TargetsList": "",
                "SharedProductsList": "",
                "SharedTargetsList": "",
                "TestTargetBlock": "",
                "OpenApiDependencies": "",
            ]
        )
        XCTAssertEqual(result.unresolvedVariables, [])
        XCTAssertTrue(result.output.contains("name: \"IAMContext\""))
        XCTAssertTrue(result.output.contains("Generated by Genesis v0.0.1-test"))
        XCTAssertTrue(result.output.contains("from: \"0.3.0\""))
        XCTAssertTrue(result.output.contains(".macOS(.v15)"))
        XCTAssertFalse(result.output.contains(".iOS"))
        XCTAssertTrue(result.output.contains("swift-tools-version: 6.0"))
    }
}
